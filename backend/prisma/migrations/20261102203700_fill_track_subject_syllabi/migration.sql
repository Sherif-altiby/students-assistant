INSERT INTO "study_units" ("id", "title", "order", "subject_id")
SELECT
  gen_random_uuid()::text,
  syllabus."unit_title",
  syllabus."unit_order",
  subject."id"
FROM (
  SELECT DISTINCT "subject_title", "unit_order", "unit_title"
  FROM "_track_syllabus"
) AS syllabus
JOIN "study_subjects" AS subject ON subject."title" = syllabus."subject_title"
ON CONFLICT ("subject_id", "order") DO NOTHING;

INSERT INTO "study_lessons" ("id", "title", "order", "unit_id")
SELECT
  gen_random_uuid()::text,
  syllabus."lesson_title",
  syllabus."lesson_order",
  unit."id"
FROM "_track_syllabus" AS syllabus
JOIN "study_subjects" AS subject ON subject."title" = syllabus."subject_title"
JOIN "study_units" AS unit
  ON unit."subject_id" = subject."id"
  AND unit."order" = syllabus."unit_order"
ON CONFLICT ("unit_id", "order") DO NOTHING;

